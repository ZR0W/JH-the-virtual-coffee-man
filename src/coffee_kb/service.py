"""Install and manage the two long-running components as systemd *user* units (Linux only).

* **collector** — ``coffee-kb-collector.timer`` fires ``coffee-kb-collector.service`` once a
  day at a randomized time; the service runs ``coffee-kb collector run``.
* **web** — ``coffee-kb-web.service`` runs ``coffee-kb web serve`` permanently.

Unit files are generated here (no templates to edit) and written to
``~/.config/systemd/user/``. Nothing outside the user's home is touched; the only root step,
``loginctl enable-linger``, is printed for the user to run once. Everything here is a thin,
explicit wrapper around ``systemctl --user``; on other platforms these commands explain that and
do nothing.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

COLLECTOR = "coffee-kb-collector"
WEB = "coffee-kb-web"
COLLECTOR_ON_CALENDAR = "*-*-* 03:00"
COLLECTOR_RANDOM_DELAY = "2h"


class ServiceError(RuntimeError):
    pass


@dataclass(frozen=True)
class Layout:
    repo_dir: Path  # where config.toml lives; WorkingDirectory of every unit
    uv: Path  # absolute path of the uv binary
    unit_dir: Path  # ~/.config/systemd/user

    @property
    def venv_cli(self) -> Path:
        """The project's own ``coffee-kb`` entry point (created by ``uv sync``)."""
        return self.repo_dir / ".venv" / "bin" / "coffee-kb"


def default_layout(config_path: Path) -> Layout:
    uv = shutil.which("uv") or str(Path.home() / ".local" / "bin" / "uv")
    xdg = os.environ.get("XDG_CONFIG_HOME") or str(Path.home() / ".config")
    return Layout(
        repo_dir=Path(config_path).resolve().parent,
        uv=Path(uv),
        unit_dir=Path(xdg) / "systemd" / "user",
    )


def _config_arg(layout: Layout, config_path: Path) -> str:
    cfg = Path(config_path).resolve()
    return "" if cfg == layout.repo_dir / "config.toml" else f" --config {cfg}"


# --- unit rendering ---------------------------------------------------------------------------


def render_collector_service(layout: Layout, config_path: Path) -> str:
    uv = layout.uv
    cfg = _config_arg(layout, config_path)
    return f"""# Generated by `coffee-kb collector install`. Re-run that command instead of editing.
#
# One run: upgrade yt-dlp (failure tolerated) -> `coffee-kb collector run`, which does
# discover (weekly) -> fetch --wait-for-cap (up to 30 videos, 60-120 s apart) -> normalize,
# logging to data/logs/coffee-kb.log. Exit 75 = block signal or cooldown latch; never retried.

[Unit]
Description=coffee-kb collector (daily capped YouTube caption/metadata collection)

[Service]
Type=oneshot
WorkingDirectory={layout.repo_dir}
Nice=10
IOSchedulingClass=idle
TimeoutStartSec=6h
Restart=no
ExecStartPre=-{uv} lock --upgrade-package yt-dlp
ExecStartPre=-{uv} sync
ExecStart={uv} run coffee-kb{cfg} collector run
"""


def render_collector_timer() -> str:
    return f"""# Generated by `coffee-kb collector install`.
# Daily at a randomized time (server local time); a day missed while the machine was off runs
# at the next boot.

[Unit]
Description=Daily trigger for coffee-kb collector

[Timer]
OnCalendar={COLLECTOR_ON_CALENDAR}
RandomizedDelaySec={COLLECTOR_RANDOM_DELAY}
Persistent=true

[Install]
WantedBy=timers.target
"""


def render_web_service(layout: Layout, config_path: Path) -> str:
    cfg = _config_arg(layout, config_path)
    return f"""# Generated by `coffee-kb web install`. Re-run that command instead of editing.
# Read-only status web app: never talks to YouTube and cannot start a fetch.
#
# Type=notify: the app tells systemd READY=1 once it is listening, so
# `systemctl --user start|restart coffee-kb-web` waits for that and exits non-zero if the
# app dies or isn't ready within TimeoutStartSec. ExecStart runs the venv's entry point
# directly (no `uv run` wrapper) so the app is the main process systemd accepts READY from.

[Unit]
Description=coffee-kb web (read-only status dashboard)

[Service]
Type=notify
WorkingDirectory={layout.repo_dir}
ExecStart={layout.venv_cli}{cfg} web serve
TimeoutStartSec=30
Restart=on-failure
RestartSec=10
Nice=5

[Install]
WantedBy=default.target
"""


# --- systemctl ------------------------------------------------------------------------------


def _require_linux() -> None:
    if not sys.platform.startswith("linux") or shutil.which("systemctl") is None:
        raise ServiceError(
            "systemd user services are only available on Linux (the home server). On this "
            "machine use `coffee-kb collector run` / `coffee-kb web serve` directly."
        )


def systemctl(*args: str, check: bool = True) -> subprocess.CompletedProcess[str]:
    """``systemctl --user ...`` (patched out in tests)."""
    proc = subprocess.run(
        ["systemctl", "--user", *args], capture_output=True, text=True, check=False
    )
    if check and proc.returncode != 0:
        raise ServiceError(f"systemctl --user {' '.join(args)} failed: {proc.stderr.strip()}")
    return proc


def linger_enabled() -> bool | None:
    user = os.environ.get("USER") or os.environ.get("LOGNAME")
    if not user or shutil.which("loginctl") is None:
        return None
    proc = subprocess.run(
        ["loginctl", "show-user", user, "-p", "Linger", "--value"],
        capture_output=True,
        text=True,
        check=False,
    )
    return proc.stdout.strip() == "yes" if proc.returncode == 0 else None


def _write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def _linger_note() -> str | None:
    if linger_enabled() is False:
        return (
            "Linger is OFF, so user services stop when you log out. Run once:\n"
            '  sudo loginctl enable-linger "$USER"'
        )
    return None


def install_collector(layout: Layout, config_path: Path) -> list[str]:
    _require_linux()
    if not layout.uv.exists():
        raise ServiceError(f"uv not found at {layout.uv}; install uv first")
    _write(layout.unit_dir / f"{COLLECTOR}.service", render_collector_service(layout, config_path))
    _write(layout.unit_dir / f"{COLLECTOR}.timer", render_collector_timer())
    systemctl("daemon-reload")
    systemctl("enable", "--now", f"{COLLECTOR}.timer")
    msgs = [f"Installed and enabled {COLLECTOR}.timer (daily 03:00 + random 0-2 h)."]
    if note := _linger_note():
        msgs.append(note)
    return msgs


def install_web(layout: Layout, config_path: Path) -> list[str]:
    _require_linux()
    if not layout.venv_cli.exists():
        raise ServiceError(f"{layout.venv_cli} not found; run `uv sync` in {layout.repo_dir} first")
    _write(layout.unit_dir / f"{WEB}.service", render_web_service(layout, config_path))
    systemctl("daemon-reload")
    systemctl("enable", "--now", f"{WEB}.service")
    # Type=notify: this blocks until the app reports READY=1 and fails if it doesn't.
    systemctl("restart", f"{WEB}.service")  # pick up code/config changes on re-install
    msgs = [f"Installed and started {WEB}.service (it reported ready)."]
    if note := _linger_note():
        msgs.append(note)
    return msgs


def uninstall(layout: Layout, units: list[str]) -> list[str]:
    _require_linux()
    msgs = []
    for unit in units:
        systemctl("disable", "--now", unit, check=False)
        path = layout.unit_dir / unit
        if path.exists():
            path.unlink()
            msgs.append(f"Removed {path}")
    systemctl("daemon-reload", check=False)
    return msgs or ["Nothing was installed."]


def unit_properties(unit: str, *props: str) -> dict[str, str]:
    if not sys.platform.startswith("linux") or shutil.which("systemctl") is None:
        return {}
    args = ["show", unit]
    for p in props:
        args += ["-p", p]
    proc = systemctl(*args, check=False)
    out: dict[str, str] = {}
    for line in proc.stdout.splitlines():
        if "=" in line:
            k, v = line.split("=", 1)
            out[k] = v
    return out


def collector_unit_state() -> dict[str, str]:
    timer = unit_properties(
        f"{COLLECTOR}.timer", "ActiveState", "NextElapseUSecRealtime", "LastTriggerUSec"
    )
    service = unit_properties(f"{COLLECTOR}.service", "ActiveState", "Result", "ExecMainStatus")
    return {
        "timer": timer.get("ActiveState", ""),
        "next_run": timer.get("NextElapseUSecRealtime", ""),
        "last_trigger": timer.get("LastTriggerUSec", ""),
        "service": service.get("ActiveState", ""),
        "last_result": service.get("Result", ""),
        "last_exit_status": service.get("ExecMainStatus", ""),
    }


def start_collector_now() -> None:
    _require_linux()
    systemctl("start", "--no-block", f"{COLLECTOR}.service")
